"""Held-out evaluation: does a generated suite catch faults it never saw?

The number that matters is not how many discovery faults a condition closed --
it was shown those. It is how the resulting suite performs on *held-out*
mutants, frozen before generation and never revealed to the agent.

Two properties are measured for every suite:

* **mutation score on held-out faults** -- the primary metric;
* **line/branch coverage** -- reported alongside, to show the two come apart.

Suites are evaluated in isolation: the subject's own expert tests are NOT run,
otherwise they would kill nearly everything and the comparison would measure
semver's testers rather than ours.
"""

from __future__ import annotations

import ast
import json
import re
import subprocess
import sys
import os
from dataclasses import dataclass, field, asdict
from pathlib import Path

from ..mutation.models import Mutant, MutantStatus
from ..verification.runner import SubjectRunner

SUITE_PATH = "tests/test_placebo_suite.py"

_HEADER = '''"""Generated by the Placebo evaluation harness.

The provenance of each candidate is recorded above it. Whether a test is
oracle-admitted or merely a green baseline candidate is recorded separately in
the experiment results; this file does not make that claim on its own.
"""

import pytest
import semver

'''


@dataclass
class SuiteScore:
    """Held-out performance of one suite."""

    name: str
    tests: int
    held_out_total: int
    killed: list[str] = field(default_factory=list)
    survived: list[str] = field(default_factory=list)
    invalid: list[str] = field(default_factory=list)
    clean_passes: bool = True
    line_coverage: float = 0.0
    branch_coverage: float = 0.0
    suite_runtime_s: float = 0.0

    @property
    def scorable(self) -> int:
        return len(self.killed) + len(self.survived)

    @property
    def mutation_score(self) -> float:
        return len(self.killed) / self.scorable if self.scorable else 0.0

    def to_dict(self) -> dict:
        d = asdict(self)
        d["mutation_score"] = round(self.mutation_score, 4)
        d["scorable"] = self.scorable
        return d


def assemble_suite(
    admitted: list[tuple[Mutant, str]], full_source: str, *, fault_claim: bool = True
) -> str:
    """Merge admitted candidate tests into one importable suite file.

    Each candidate defines ``test_placebo_candidate``; they are renamed so all
    of them can coexist and annotated with their evaluation provenance. For an
    oracle-admitted candidate, that provenance is the fault it detected.
    """
    parts = [_HEADER]
    for i, (mutant, code) in enumerate(admitted, 1):
        # Parse candidates independently. Concatenating a malformed candidate
        # with valid ones makes the whole suite unparseable and previously let
        # the green-repair stage misreport invalid baseline tests as retained.
        try:
            tree = ast.parse(code)
        except SyntaxError:
            continue

        test_nodes = [
            node for node in tree.body
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
            and node.name.startswith("test_")
        ]
        for j, node in enumerate(test_nodes, 1):
            body = ast.get_source_segment(code, node)
            if not body:
                continue
            suffix = f"_{j:02d}" if len(test_nodes) > 1 else ""
            name = f"test_placebo_{i:02d}_{_slug(mutant.qualname)}{suffix}"
            body = re.sub(
                r"\bdef\s+test_\w+\s*\(", f"def {name}(", body, count=1
            )
            provenance = (
                f"# fault detected: {mutant.label}"
                if fault_claim
                else f"# evaluation case (not a detection claim): {mutant.label}"
            )
            parts.append(
                f"{provenance}\n"
                f"# mutant id: {mutant.id}\n"
                f"{body.strip()}\n"
            )
    return "\n\n".join(parts) + "\n"


def _slug(qualname: str) -> str:
    return re.sub(r"\W+", "_", qualname).strip("_").lower()


def measure_coverage(runner: SubjectRunner, suite_code: str) -> tuple[float, float]:
    """Line and branch coverage of `semver/version.py` under this suite alone."""
    with runner.extra_tests({SUITE_PATH: suite_code}):
        env = dict(os.environ)
        env["PYTHONPATH"] = str(runner.workspace)
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        cmd = [
            sys.executable, "-m", "pytest", SUITE_PATH,
            "-q", "--tb=no", "-p", "no:cacheprovider", "--no-header",
            "-o", "addopts=",
            "--cov=semver.version", "--cov-branch",
            "--cov-report=json:.placebo-cov.json",
        ]
        cov_file = runner.workspace / ".placebo-cov.json"
        cov_file.unlink(missing_ok=True)
        completed = subprocess.run(
            cmd, cwd=runner.workspace, env=env,
            capture_output=True, text=True, timeout=600,
        )
        if completed.returncode != 0 or not cov_file.exists():
            return (0.0, 0.0)
        data = json.loads(cov_file.read_text(encoding="utf-8"))
        cov_file.unlink(missing_ok=True)
        totals = data.get("totals", {})
        return (
            round(totals.get("percent_covered", 0.0), 2),
            round(totals.get("covered_branches", 0)
                  / max(1, totals.get("num_branches", 1)) * 100, 2),
        )


def evaluate_suite(
    runner: SubjectRunner,
    name: str,
    suite_code: str,
    held_out: list[Mutant],
    n_tests: int,
    with_coverage: bool = True,
) -> SuiteScore:
    """Score one suite against the frozen held-out mutants."""
    score = SuiteScore(name=name, tests=n_tests, held_out_total=len(held_out))

    if not suite_code.strip() or n_tests == 0:
        score.survived = [m.id for m in held_out]
        score.clean_passes = True
        return score

    # Sanity: the suite must be green on correct code before it can be
    # credited with detecting anything.
    with runner.extra_tests({SUITE_PATH: suite_code}):
        clean = runner.run_suite([SUITE_PATH], tb="short")
    score.clean_passes = clean.passed
    score.suite_runtime_s = round(clean.duration_s, 2)
    if not clean.passed:
        # A suite that is red on correct code is not a usable suite. Report it
        # rather than quietly scoring it.
        score.survived = [m.id for m in held_out]
        return score

    for mutant in held_out:
        run = runner.run_mutant(
            mutant, selection=[SUITE_PATH], extra={SUITE_PATH: suite_code}
        )
        if run.status is MutantStatus.KILLED:
            score.killed.append(mutant.id)
        elif run.status is MutantStatus.SURVIVED:
            score.survived.append(mutant.id)
        else:
            score.invalid.append(mutant.id)

    if with_coverage:
        score.line_coverage, score.branch_coverage = measure_coverage(runner, suite_code)

    return score
